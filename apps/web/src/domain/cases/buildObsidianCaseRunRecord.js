export function buildObsidianCaseRunRecord({
  caseId,
  generatedDate,
  resultJsonPath,
  summaryMarkdown,
}) {
  return [
    `# 端到端样例_${generatedDate}_${caseId}`,
    "",
    "> 生成方式：代码侧 `run:case` + `export:obsidian-case` 自动生成草稿",
    `> 样例编号：${caseId}`,
    `> 生成日期：${generatedDate}`,
    `> 对应代码结果：${resultJsonPath}`,
    "> 文档状态：可继续编辑",
    "",
    "## 0. 使用说明",
    "- 这是一份代码侧自动生成的端到端记录草稿。",
    "- 下面的“代码侧运行底稿”来自当前 case-run 导出结果。",
    "- 你后续应继续补：真实样本观察、规则影响、产品判断、后续动作。",
    "",
    "## 1. 代码侧运行底稿",
    "",
    summaryMarkdown.trim(),
    "",
    "## 2. 人工补充观察",
    "- 这次运行最值得关注的点：",
    "- 和预期不一致的地方：",
    "- 哪一张卡最像真实平台内容：",
    "- 第二轮是否真的更贴需求：",
    "",
    "## 3. 对规则系统的影响",
    "- 是否需要补反馈词：",
    "- 是否需要补案例标签：",
    "- 是否需要写规则修订记录：",
    "",
    "## 4. 对产品方案的影响",
    "- 第一轮卡片结构要不要改：",
    "- 第二轮优化结构要不要改：",
    "- 输入字段是否需要增减：",
    "",
    "## 5. 后续动作",
    "- [ ] 更新平台案例文件",
    "- [ ] 更新代码侧 case 文件",
    "- [ ] 更新测试记录",
    "- [ ] 更新规则修订记录",
    "- [ ] 更新当前版本摘要",
    "",
  ].join("\n");
}
